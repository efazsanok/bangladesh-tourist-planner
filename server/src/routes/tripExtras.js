const express = require('express');
const PDFDocument = require('pdfkit');
const { body, param } = require('express-validator');
const pool = require('../config/db');
const asyncHandler = require('../utils/asyncHandler');
const validate = require('../middleware/validate');
const { authenticate } = require('../middleware/auth');
const { DATE_RE, addDays, todayStr } = require('../utils/dates');
const { getOwnedTrip, getTripItems } = require('../utils/itinerary');

const router = express.Router();
const idParam = param('id').isInt({ min: 1 });

router.post(
    '/trips/:id/duplicate',
    authenticate, idParam,
    body('start_date').optional({ values: 'falsy' }).matches(DATE_RE).withMessage('Start date must be YYYY-MMDD'), 
    body('title').optional({ values: 'falsy' }).isLength({ min: 3, max: 120 }).withMessage('Title must be 3120 characters'), 
  validate,
        asyncHandler(async (req, res) => {
            const trip = await getOwnedTrip(req.user.id, req.params.id);
            const items = await getTripItems(trip.id);
            const start = req.body.start_date || todayStr();
            const end = addDays(start, trip.days - 1);
            const title = req.body.title || `Copy of ${trip.title}`.slice(0, 120);

            const conn = await pool.getConnection();
            try {
                await conn.beginTransaction();
                const [r] = await conn.query(
                    'INSERT INTO trips (user_id, title, start_date, end_date, travelers, total_budget) VALUES (?, ?, ?, ?, ?, ?)', 
                        [req.user.id, title, start, end, trip.travelers, trip.total_budget] 
      );
for (const i of items) {
    await conn.query(
        `INSERT INTO itinerary_items (trip_id, destination_id, attraction_id, day_number, position, title, 
activity_type, start_time, est_cost, notes) 
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        [r.insertId, i.destination_id, i.attraction_id, i.day_number, i.position, i.title,
        i.activity_type, i.start_time, i.est_cost, i.notes]
    );
}
await conn.commit();
res.status(201).json({ id: r.insertId }); 
    } catch (err) {
    await conn.rollback();
    throw err;
} finally {
    conn.release();
} 
  }) 
);

router.get('/trips/:id/pdf', authenticate, idParam, validate, asyncHandler(async (req, res) => {
    const trip = await getOwnedTrip(req.user.id, req.params.id);
    const items = await getTripItems(trip.id);
    const [expenses] = await pool.query('SELECT category, SUM(amount) AS total FROM expenses WHERE trip_id = ? GROUP BY category', [trip.id]); 
  
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="trip-${trip.id}-summary.pdf"`);
    doc.pipe(res);

    doc.fontSize(22).fillColor('#065f46').text(trip.title);
    doc.moveDown(0.3).fontSize(11).fillColor('#334155');
    doc.text(`Dates: ${trip.start_date} to ${trip.end_date} (${trip.days} days)`);
    doc.text(`Travelers: ${trip.travelers}`);
    doc.text(`Planned budget: BDT ${trip.total_budget.toLocaleString('en-US')}`);
    doc.moveDown();

    for (let day = 1; day <= trip.days; day++) {
        doc.fontSize(14).fillColor('#065f46').text(`Day ${day} - ${addDays(trip.start_date, day - 1)}`);
        const list = items.filter((i) => i.day_number === day);
        if (!list.length) doc.fontSize(10).fillColor('#64748b').text('  No activities planned');
        list.forEach((i) => {
            const time = i.start_time ? i.start_time.slice(0, 5) : '--:--';
            doc.fontSize(10).fillColor('#0f172a').text(`  ${time}  ${i.title} (${i.destination_name}, ${i.activity_type})  - BDT ${i.est_cost}`);
            if (i.notes) doc.fillColor('#64748b').text(`        Note: ${i.notes}`);
        });
        doc.moveDown(0.6);
    }

    const planned = items.reduce((s, i) => s + i.est_cost, 0);
    doc.fontSize(14).fillColor('#065f46').text('Budget summary');
    doc.fontSize(10).fillColor('#0f172a').text(`Estimated activity costs: BDT ${planned}`);
    if (expenses.length) {
        const spent = expenses.reduce((s, e) => s + Number(e.total), 0);
        expenses.forEach((e) => doc.text(`  ${e.category}: BDT ${Number(e.total)}`));
        doc.text(`Total spent: BDT ${spent}  |  Remaining: BDT ${trip.total_budget - spent}`);
    }
    doc.moveDown().fontSize(8).fillColor('#94a3b8').text('Generated by Weather & Budget-Smart Bangladesh Tourist Planner'); 
    doc.end();
}));

module.exports = router;